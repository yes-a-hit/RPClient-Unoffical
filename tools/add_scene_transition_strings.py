def esc(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


for key, mapping in KEYS.items():
    for folder, value in mapping.items():
        path = os.path.join(ROOT, folder, 'strings.xml')
        if not os.path.exists(path):
            print('MISSING', path)
            continue
        t = io.open(path, encoding='utf-8').read()
        if 'name="%s"' % key in t:
            print('SKIP', folder, key)
            continue
        entry = '    <string name="%s">%s</string>\n' % (key, esc(value))
        t = t.replace('</resources>', entry + '</resources>', 1)
        io.open(path, 'w', encoding='utf-8', newline='').write(t)
        print('OK', folder, key)
